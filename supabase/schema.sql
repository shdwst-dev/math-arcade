-- 1. TABLA DE PERFILES DE USUARIO (Vinculada a auth.users de Supabase)
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    username TEXT UNIQUE NOT NULL,
    full_name TEXT,
    total_games_played INTEGER NOT NULL DEFAULT 0,
    total_wins INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. TABLA DE RÉCORDS PERSONALES (Mejores puntuaciones por tema/subtema/juego/dificultad)
CREATE TABLE IF NOT EXISTS public.high_scores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    topic TEXT NOT NULL,
    subtopic TEXT NOT NULL DEFAULT 'todos',
    game TEXT NOT NULL,
    difficulty TEXT NOT NULL DEFAULT 'Normal',
    best_score INTEGER NOT NULL DEFAULT 0,
    attempts INTEGER NOT NULL DEFAULT 1,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT high_scores_unique_entry UNIQUE (user_id, topic, subtopic, game, difficulty)
);

-- 3. TABLA DE HISTORIAL DE PARTIDAS (Para seguimiento del progreso del alumno)
CREATE TABLE IF NOT EXISTS public.game_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    topic TEXT NOT NULL,
    subtopic TEXT NOT NULL DEFAULT 'todos',
    game TEXT NOT NULL,
    difficulty TEXT NOT NULL DEFAULT 'Normal',
    score INTEGER NOT NULL,
    won BOOLEAN NOT NULL DEFAULT FALSE,
    played_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Índices para consultas rápidas de ranking e historial
CREATE INDEX IF NOT EXISTS idx_high_scores_leaderboard ON public.high_scores (topic, game, best_score DESC);
CREATE INDEX IF NOT EXISTS idx_high_scores_user ON public.high_scores (user_id);
CREATE INDEX IF NOT EXISTS idx_game_history_user_date ON public.game_history (user_id, played_at DESC);

-- ============================================================================
-- 4. TRIGGER AUTOMÁTICO PARA CREAR EL PERFIL AL REGISTRARSE
-- ============================================================================
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER SET search_path = public
AS $$
DECLARE
    v_username TEXT;
    v_full_name TEXT;
BEGIN
    v_username := COALESCE(
         NULLIF(TRIM(NEW.raw_user_meta_data->>'username'), ''),
        SPLIT_PART(NEW.email, '@', 1)
    );
    -- Limpiar caracteres raros y limitar a 20 caracteres
    v_username := LEFT(REGEXP_REPLACE(v_username, '[^a-zA-Z0-9_.ñÑáéíóúÁÉÍÓÚ-]', '', 'g'), 20);
    IF CHAR_LENGTH(v_username) < 3 THEN
        v_username := 'jugador_' || SUBSTR(NEW.id::TEXT, 1, 6);
    END IF;
    -- Si el nombre ya existe, agregar un sufijo para no romper el registro
    IF EXISTS (SELECT 1 FROM public.profiles WHERE username = v_username) THEN
        v_username := LEFT(v_username, 15) || '_' || SUBSTR(NEW.id::TEXT, 1, 4);
    END IF;
    v_full_name := COALESCE(NEW.raw_user_meta_data->>'full_name', v_username);

    INSERT INTO public.profiles (id, username, full_name)
    VALUES (NEW.id, v_username, v_full_name)
    ON CONFLICT (id) DO NOTHING;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- ============================================================================
-- 5. FUNCIÓN RPC PARA GUARDAR PARTIDA, ACTUALIZAR RÉCORD Y ESTADÍSTICAS
-- ============================================================================
CREATE OR REPLACE FUNCTION public.record_game_result(
    p_topic TEXT,
    p_subtopic TEXT,
    p_game TEXT,
    p_difficulty TEXT,
    p_score INTEGER,
    p_won BOOLEAN
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER SET search_path = public
AS $$
DECLARE
    v_user_id UUID := auth.uid();
    v_subtopic TEXT := COALESCE(NULLIF(p_subtopic, ''), 'todos');
    v_difficulty TEXT := COALESCE(NULLIF(p_difficulty, ''), 'Normal');
    v_prev_best INTEGER;
    v_is_new_record BOOLEAN := FALSE;
BEGIN
    IF v_user_id IS NULL THEN
        RAISE EXCEPTION 'Usuario no autenticado';
    END IF;

    -- Validaciones básicas para evitar datos basura o puntuaciones imposibles
    IF p_topic NOT IN ('fundamentos', 'diferencial', 'integral')
       OR p_game NOT IN ('memory', 'bomb', 'race')
       OR v_difficulty NOT IN ('Fácil', 'Normal', 'Difícil') THEN
        RAISE EXCEPTION 'Datos de partida inválidos';
    END IF;
    IF p_score IS NULL OR p_score < -1000 OR p_score > 5000 THEN
        RAISE EXCEPTION 'Puntuación fuera de rango';
    END IF;

    -- 1. Insertar en el historial de partidas
    INSERT INTO public.game_history (user_id, topic, subtopic, game, difficulty, score, won)
    VALUES (v_user_id, p_topic, v_subtopic, p_game, v_difficulty, p_score, p_won);

    -- 2. Verificar récord previo
    SELECT best_score INTO v_prev_best
    FROM public.high_scores
    WHERE user_id = v_user_id
      AND topic = p_topic
      AND subtopic = v_subtopic
      AND game = p_game
      AND difficulty = v_difficulty;

    IF v_prev_best IS NULL OR p_score > v_prev_best THEN
        v_is_new_record := TRUE;
    END IF;

    -- 3. Upsert en high_scores
    INSERT INTO public.high_scores (user_id, topic, subtopic, game, difficulty, best_score, attempts, updated_at)
    VALUES (v_user_id, p_topic, v_subtopic, p_game, v_difficulty, p_score, 1, NOW())
    ON CONFLICT (user_id, topic, subtopic, game, difficulty)
    DO UPDATE SET
        best_score = GREATEST(public.high_scores.best_score, EXCLUDED.best_score),
        attempts = public.high_scores.attempts + 1,
        updated_at = NOW();

    -- 4. Actualizar contadores del perfil
    UPDATE public.profiles
    SET total_games_played = total_games_played + 1,
        total_wins = total_wins + (CASE WHEN p_won THEN 1 ELSE 0 END),
        updated_at = NOW()
    WHERE id = v_user_id;

    RETURN jsonb_build_object(
        'is_new_record', v_is_new_record,
        'best_score', GREATEST(COALESCE(v_prev_best, p_score), p_score)
    );
END;
$$;

-- Solo usuarios con sesión pueden llamar a la función
REVOKE EXECUTE ON FUNCTION public.record_game_result(TEXT, TEXT, TEXT, TEXT, INTEGER, BOOLEAN) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.record_game_result(TEXT, TEXT, TEXT, TEXT, INTEGER, BOOLEAN) TO authenticated;

-- ============================================================================
-- 6. POLÍTICAS DE SEGURIDAD (ROW LEVEL SECURITY - RLS)
-- ============================================================================
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.high_scores ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.game_history ENABLE ROW LEVEL SECURITY;

-- Políticas para profiles: cualquiera puede leer nombres para el ranking; cada usuario edita su perfil
DROP POLICY IF EXISTS "Perfiles visibles para todos" ON public.profiles;
CREATE POLICY "Perfiles visibles para todos"
    ON public.profiles FOR SELECT
    USING (true);

DROP POLICY IF EXISTS "Usuarios pueden insertar su propio perfil" ON public.profiles;
CREATE POLICY "Usuarios pueden insertar su propio perfil"
    ON public.profiles FOR INSERT
    WITH CHECK (auth.uid() = id);

DROP POLICY IF EXISTS "Usuarios pueden actualizar su propio perfil" ON public.profiles;
CREATE POLICY "Usuarios pueden actualizar su propio perfil"
    ON public.profiles FOR UPDATE
    USING (auth.uid() = id);

-- El usuario solo puede editar su nombre; los contadores los actualiza record_game_result
REVOKE UPDATE ON public.profiles FROM anon, authenticated;
GRANT UPDATE (username, full_name) ON public.profiles TO authenticated;

-- Políticas para high_scores: lectura pública para ranking global; escritura sólo del propio usuario
DROP POLICY IF EXISTS "Récords visibles para ranking global" ON public.high_scores;
CREATE POLICY "Récords visibles para ranking global"
    ON public.high_scores FOR SELECT
    USING (true);

-- Sin políticas de INSERT/UPDATE: los récords solo se escriben a través de
-- record_game_result (que valida los datos), así nadie puede inventarse un récord.
DROP POLICY IF EXISTS "Usuarios insertan sus propios récords" ON public.high_scores;
DROP POLICY IF EXISTS "Usuarios actualizan sus propios récords" ON public.high_scores;

DROP POLICY IF EXISTS "Usuarios borran sus propios récords" ON public.high_scores;
CREATE POLICY "Usuarios borran sus propios récords"
    ON public.high_scores FOR DELETE
    USING (auth.uid() = user_id);

-- Políticas para game_history: cada usuario ve e inserta su propio historial
DROP POLICY IF EXISTS "Usuarios ven su propio historial" ON public.game_history;
CREATE POLICY "Usuarios ven su propio historial"
    ON public.game_history FOR SELECT
    USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Usuarios insertan su propio historial" ON public.game_history;

DROP POLICY IF EXISTS "Usuarios borran su propio historial" ON public.game_history;
CREATE POLICY "Usuarios borran su propio historial"
    ON public.game_history FOR DELETE
    USING (auth.uid() = user_id);
